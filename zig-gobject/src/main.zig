// Detail holds the widgets the row-selected handler updates.
// The ingredient/step label slots are fixed at the largest
// counts in the data (7 ingredients, 5 steps); slots beyond
// a recipe's counts are hidden. Formatted lines are allocated
// from the arena; gtk_label_set_text copies them, so the
// arena is never freed during the app's lifetime.
const Detail = struct {
    title: *gtk.Label,
    description: *gtk.Label,
    servings: *gtk.Label,
    notes: *gtk.Label,
    ingredient_labels: [7]*gtk.Label,
    step_labels: [5]*gtk.Label,
    arena: std.heap.ArenaAllocator,
};

// fmtZ formats with a trailing NUL and returns a sentinel slice,
// which is what the gtk setText/new calls take. (std.fmt has no
// allocPrintZ in Zig 0.17.)
fn fmtZ(alloc: std.mem.Allocator, comptime fmt: []const u8, args: anytype) [:0]const u8 {
    const s = std.fmt.allocPrint(alloc, fmt ++ "\x00", args) catch @panic("oom");
    return s[0 .. s.len - 1 :0];
}

fn show_recipe(detail: *Detail, recipe: db.Recipe) void {
    const alloc = detail.arena.allocator();
    gtk.Label.setText(detail.title, recipe.title);
    gtk.Label.setText(detail.description, recipe.description);
    gtk.Label.setText(detail.servings, fmtZ(alloc, "Servings: {d}", .{recipe.servings}));

    for (detail.ingredient_labels, 0..) |label, i| {
        if (i < recipe.ingredients.len) {
            const ing = recipe.ingredients[i];
            const line = if (ing.unit.len == 0)
                fmtZ(alloc, "{s} {s}", .{ ing.amount, ing.name })
            else
                fmtZ(alloc, "{s} {s} {s}", .{ ing.amount, ing.unit, ing.name });
            gtk.Label.setText(label, line);
            gtk.Widget.setVisible(label.as(gtk.Widget), 1);
        } else {
            gtk.Widget.setVisible(label.as(gtk.Widget), 0);
        }
    }

    for (detail.step_labels, 0..) |label, i| {
        if (i < recipe.steps.len) {
            const line = fmtZ(alloc, "{d}. {s}", .{ i + 1, recipe.steps[i] });
            gtk.Label.setText(label, line);
            gtk.Widget.setVisible(label.as(gtk.Widget), 1);
        } else {
            gtk.Widget.setVisible(label.as(gtk.Widget), 0);
        }
    }

    gtk.Label.setText(detail.notes, recipe.notes);
}

// clear_detail empties the detail pane (used when the
// last recipe has been deleted).
fn clear_detail(detail: *Detail) void {
    gtk.Label.setText(detail.title, "");
    gtk.Label.setText(detail.description, "");
    gtk.Label.setText(detail.servings, "");
    for (detail.ingredient_labels) |label| {
        gtk.Label.setText(label, "");
        gtk.Widget.setVisible(label.as(gtk.Widget), 0);
    }
    for (detail.step_labels) |label| {
        gtk.Label.setText(label, "");
        gtk.Widget.setVisible(label.as(gtk.Widget), 0);
    }
    gtk.Label.setText(detail.notes, "");
}

fn on_search_changed(_: *gtk.SearchEntry, _: *gtk.Window) callconv(.c) void {
    rebuild_list();
    if (filtered.items.len > 0) {
        selected_id = db.recipes[filtered.items[0]].id;
        show_recipe(detail_ptr, db.recipes[filtered.items[0]]);
        if (gtk.ListBox.getRowAtIndex(main_list_box, 0)) |row| {
            gtk.ListBox.selectRow(main_list_box, row);
        }
    } else {
        selected_id = -1;
        clear_detail(detail_ptr);
    }
}

fn on_row_selected(_: *gtk.ListBox, row: ?*gtk.ListBoxRow, detail: *Detail) callconv(.c) void {
    const r = row orelse return;
    const index = gtk.ListBoxRow.getIndex(r);
    if (index < 0 or index >= filtered.items.len) return;
    const recipe_index = filtered.items[@intCast(index)];
    selected_id = db.recipes[recipe_index].id;
    show_recipe(detail, db.recipes[recipe_index]);
}

fn detail_label() *gtk.Label {
    const label = gtk.Label.new("");
    gtk.Label.setXalign(label, 0);
    return label;
}

// The main window's list box (rebuilt after an insert).
// Only one add window exists at a time (it is modal), so
// the form handlers share active_form.
var main_list_box: *gtk.ListBox = undefined;
var active_form: ?*Form = null;

// Id of the recipe currently shown in the detail pane (-1
// when none is selected); the Edit button acts on it.
var selected_id: i64 = -1;

// Id awaiting confirmation in the delete dialog (-1 when
// no dialog is open); the dialog is modal, so this is
// never shared between two dialogs.
var pending_delete_id: i64 = -1;

var detail_ptr: *Detail = undefined;

var search_entry: *gtk.SearchEntry = undefined;

// Indices into db.recipes, in list order, after applying
// the search filter. Rebuilt by apply_filter on every
// list rebuild.
var filtered: std.ArrayList(usize) = .empty;

const IngredientRow = struct {
    box: *gtk.Widget,
    amount: *gtk.Entry,
    unit: *gtk.Entry,
    name: *gtk.Entry,
};

const StepRow = struct {
    box: *gtk.Widget,
    entry: *gtk.Entry,
};

// Form holds the add window's widgets. Heap-allocated like
// Detail: the window outlives the handler that opens it.
// Row lists come from the form's arena, never freed.
const Form = struct {
    window: *gtk.Window,
    edit_id: i64,
    title: *gtk.Entry,
    description: *gtk.Entry,
    servings: *gtk.SpinButton,
    notes: *gtk.Entry,
    error_label: *gtk.Label,
    ing_box: *gtk.Box,
    step_box: *gtk.Box,
    ing_rows: std.ArrayList(IngredientRow),
    step_rows: std.ArrayList(StepRow),
    arena: std.heap.ArenaAllocator,
};

// Entry text as a sentinel slice. This points at the
// entry's own buffer, so it is only valid while the entry
// lives — fine here, since saving binds (SQLITE_STATIC)
// and steps before the form closes.
fn entryText(entry: *gtk.Entry) [:0]const u8 {
    return std.mem.span(gtk.Editable.getText(entry.as(gtk.Editable)));
}

fn isBlank(text: [:0]const u8) bool {
    return std.mem.trim(u8, text, " \t\r\n").len == 0;
}

fn add_list_row(list_box: *gtk.ListBox, title: [:0]const u8) void {
    var row_label = gtk.Label.new(title);
    gtk.Label.setXalign(row_label, 0);
    gtk.ListBox.append(list_box, row_label.as(gtk.Widget));
}

// title_matches_search is the list filter, mirroring
// cpp-gtk4's search.h: case-insensitive substring match
// on the recipe TITLE only; an empty query matches
// everything; the query is NOT trimmed.
fn title_matches_search(title: [:0]const u8, query: [:0]const u8) bool {
    if (query.len == 0) return true;
    if (query.len > title.len) return false;
    var i: usize = 0;
    while (i + query.len <= title.len) : (i += 1) {
        var ok = true;
        for (query, 0..) |qc, j| {
            if (std.ascii.toLower(title[i + j]) != std.ascii.toLower(qc)) {
                ok = false;
                break;
            }
        }
        if (ok) return true;
    }
    return false;
}

fn apply_filter() void {
    filtered.clearRetainingCapacity();
    const query = std.mem.span(gtk.Editable.getText(search_entry.as(gtk.Editable)));
    for (db.recipes, 0..) |recipe, i| {
        if (title_matches_search(recipe.title, query)) {
            filtered.append(std.heap.page_allocator, i) catch @panic("oom");
        }
    }
}

fn rebuild_list() void {
    apply_filter();
    gtk.ListBox.removeAll(main_list_box);
    for (filtered.items) |idx| {
        add_list_row(main_list_box, db.recipes[idx].title);
    }
}

fn add_ingredient_row(form: *Form) void {
    const alloc = form.arena.allocator();
    var row_box = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var amount = gtk.Entry.new();
    var unit = gtk.Entry.new();
    var name = gtk.Entry.new();
    gtk.Box.append(row_box, amount.as(gtk.Widget));
    gtk.Box.append(row_box, unit.as(gtk.Widget));
    gtk.Box.append(row_box, name.as(gtk.Widget));
    var remove = gtk.Button.newWithLabel("Remove");
    gtk.Box.append(row_box, remove.as(gtk.Widget));
    _ = gtk.Button.signals.clicked.connect(remove, *gtk.Widget, &on_remove_ingredient, row_box.as(gtk.Widget), .{});
    gtk.Box.append(form.ing_box, row_box.as(gtk.Widget));
    form.ing_rows.append(alloc, .{
        .box = row_box.as(gtk.Widget),
        .amount = amount,
        .unit = unit,
        .name = name,
    }) catch @panic("oom");
}

fn add_step_row(form: *Form) void {
    const alloc = form.arena.allocator();
    var row_box = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var entry = gtk.Entry.new();
    gtk.Box.append(row_box, entry.as(gtk.Widget));
    var remove = gtk.Button.newWithLabel("Remove");
    gtk.Box.append(row_box, remove.as(gtk.Widget));
    _ = gtk.Button.signals.clicked.connect(remove, *gtk.Widget, &on_remove_step, row_box.as(gtk.Widget), .{});
    gtk.Box.append(form.step_box, row_box.as(gtk.Widget));
    form.step_rows.append(alloc, .{
        .box = row_box.as(gtk.Widget),
        .entry = entry,
    }) catch @panic("oom");
}

fn on_remove_ingredient(_: *gtk.Button, row_box: *gtk.Widget) callconv(.c) void {
    const form = active_form orelse return;
    for (form.ing_rows.items, 0..) |row, i| {
        if (row.box == row_box) {
            gtk.Box.remove(form.ing_box, row_box);
            _ = form.ing_rows.orderedRemove(i);
            return;
        }
    }
}

fn on_remove_step(_: *gtk.Button, row_box: *gtk.Widget) callconv(.c) void {
    const form = active_form orelse return;
    for (form.step_rows.items, 0..) |row, i| {
        if (row.box == row_box) {
            gtk.Box.remove(form.step_box, row_box);
            _ = form.step_rows.orderedRemove(i);
            return;
        }
    }
}

fn on_add_ingredient_row(_: *gtk.Button, form: *Form) callconv(.c) void {
    add_ingredient_row(form);
}

fn on_add_step_row(_: *gtk.Button, form: *Form) callconv(.c) void {
    add_step_row(form);
}

fn on_add_save(_: *gtk.Button, form: *Form) callconv(.c) void {
    const alloc = form.arena.allocator();
    const title = entryText(form.title);
    if (isBlank(title)) {
        gtk.Label.setText(form.error_label, "Title is required.");
        return;
    }
    var ingredients: std.ArrayList(db.Ingredient) = .empty;
    for (form.ing_rows.items) |row| {
        const amount = entryText(row.amount);
        const unit = entryText(row.unit);
        const name = entryText(row.name);
        if (isBlank(amount) and isBlank(unit) and isBlank(name)) continue;
        ingredients.append(alloc, .{
            .amount = amount,
            .unit = unit,
            .name = name,
        }) catch @panic("oom");
    }
    var steps: std.ArrayList([:0]const u8) = .empty;
    for (form.step_rows.items) |row| {
        const text = entryText(row.entry);
        if (isBlank(text)) continue;
        steps.append(alloc, text) catch @panic("oom");
    }
    var recipe = db.Recipe{
        .title = title,
        .description = entryText(form.description),
        .servings = @intCast(gtk.SpinButton.getValueAsInt(form.servings)),
        .ingredients = ingredients.items,
        .steps = steps.items,
        .notes = entryText(form.notes),
    };
    var saved_id = form.edit_id;
    if (form.edit_id >= 0) {
        recipe.id = form.edit_id;
        db.updateRecipe(recipe) catch {
            if (db.load_error) |e| {
                gtk.Label.setText(form.error_label, e);
            } else {
                gtk.Label.setText(form.error_label, "Could not save the recipe.");
            }
            return;
        };
    } else {
        const id = db.insertRecipe(recipe) catch {
            if (db.load_error) |e| {
                gtk.Label.setText(form.error_label, e);
            } else {
                gtk.Label.setText(form.error_label, "Could not save the recipe.");
            }
            return;
        };
        saved_id = id;
    }
    db.reload() catch {
        if (db.load_error) |e| {
            gtk.Label.setText(form.error_label, e);
        } else {
            gtk.Label.setText(form.error_label, "Could not reload recipes.");
        }
        return;
    };
    rebuild_list();
    for (filtered.items, 0..) |idx, p| {
        if (db.recipes[idx].id == saved_id) {
            if (gtk.ListBox.getRowAtIndex(main_list_box, @intCast(p))) |row| {
                gtk.ListBox.selectRow(main_list_box, row);
            }
            break;
        }
    }
    active_form = null;
    gtk.Window.close(form.window);
}

fn on_add_cancel(_: *gtk.Button, form: *Form) callconv(.c) void {
    active_form = null;
    gtk.Window.close(form.window);
}

// openForm builds the add/edit form window. prefill is
// null for adding; for editing it is the selected recipe
// (its strings are copied into the entries immediately, so
// the value need not outlive this call), and edit_id is
// that recipe's id, or -1.
fn openForm(parent: *gtk.Window, prefill: ?db.Recipe, edit_id: i64) void {
    var form = std.heap.page_allocator.create(Form) catch @panic("oom");
    form.arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
    form.ing_rows = .empty;
    form.step_rows = .empty;
    form.edit_id = edit_id;
    active_form = form;

    var window = gtk.Window.new();
    form.window = window;
    if (edit_id >= 0) {
        gtk.Window.setTitle(window, "Edit Recipe");
    } else {
        gtk.Window.setTitle(window, "Add Recipe");
    }
    gtk.Window.setTransientFor(window, parent);
    gtk.Window.setModal(window, 1);
    gtk.Window.setDefaultSize(window, 500, 600);

    var form_box = gtk.Box.new(gtk.Orientation.vertical, 6);
    gtk.Box.append(form_box, detail_label_heading("Title:"));
    form.title = gtk.Entry.new();
    if (prefill) |r| gtk.Editable.setText(form.title.as(gtk.Editable), r.title);
    gtk.Box.append(form_box, form.title.as(gtk.Widget));
    gtk.Box.append(form_box, detail_label_heading("Description:"));
    form.description = gtk.Entry.new();
    if (prefill) |r| gtk.Editable.setText(form.description.as(gtk.Editable), r.description);
    gtk.Box.append(form_box, form.description.as(gtk.Widget));
    gtk.Box.append(form_box, detail_label_heading("Servings:"));
    form.servings = gtk.SpinButton.newWithRange(1, 100, 1);
    if (prefill) |r| gtk.SpinButton.setValue(form.servings, @floatFromInt(r.servings));
    gtk.Box.append(form_box, form.servings.as(gtk.Widget));
    gtk.Box.append(form_box, detail_label_heading("Ingredients:"));
    form.ing_box = gtk.Box.new(gtk.Orientation.vertical, 6);
    gtk.Box.append(form_box, form.ing_box.as(gtk.Widget));
    var add_ing = gtk.Button.newWithLabel("Add ingredient");
    _ = gtk.Button.signals.clicked.connect(add_ing, *Form, &on_add_ingredient_row, form, .{});
    gtk.Box.append(form_box, add_ing.as(gtk.Widget));
    if (prefill) |r| {
        for (r.ingredients) |ing| {
            add_ingredient_row(form);
            const row = &form.ing_rows.items[form.ing_rows.items.len - 1];
            gtk.Editable.setText(row.amount.as(gtk.Editable), ing.amount);
            gtk.Editable.setText(row.unit.as(gtk.Editable), ing.unit);
            gtk.Editable.setText(row.name.as(gtk.Editable), ing.name);
        }
        if (form.ing_rows.items.len == 0) add_ingredient_row(form);
    } else {
        add_ingredient_row(form);
    }
    gtk.Box.append(form_box, detail_label_heading("Steps:"));
    form.step_box = gtk.Box.new(gtk.Orientation.vertical, 6);
    gtk.Box.append(form_box, form.step_box.as(gtk.Widget));
    var add_step = gtk.Button.newWithLabel("Add step");
    _ = gtk.Button.signals.clicked.connect(add_step, *Form, &on_add_step_row, form, .{});
    gtk.Box.append(form_box, add_step.as(gtk.Widget));
    if (prefill) |r| {
        for (r.steps) |step| {
            add_step_row(form);
            const row = &form.step_rows.items[form.step_rows.items.len - 1];
            gtk.Editable.setText(row.entry.as(gtk.Editable), step);
        }
        if (form.step_rows.items.len == 0) add_step_row(form);
    } else {
        add_step_row(form);
    }
    gtk.Box.append(form_box, detail_label_heading("Notes:"));
    form.notes = gtk.Entry.new();
    if (prefill) |r| gtk.Editable.setText(form.notes.as(gtk.Editable), r.notes);
    gtk.Box.append(form_box, form.notes.as(gtk.Widget));
    form.error_label = detail_label();
    gtk.Box.append(form_box, form.error_label.as(gtk.Widget));

    var buttons = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var save = gtk.Button.newWithLabel("Save");
    _ = gtk.Button.signals.clicked.connect(save, *Form, &on_add_save, form, .{});
    gtk.Box.append(buttons, save.as(gtk.Widget));
    var cancel = gtk.Button.newWithLabel("Cancel");
    _ = gtk.Button.signals.clicked.connect(cancel, *Form, &on_add_cancel, form, .{});
    gtk.Box.append(buttons, cancel.as(gtk.Widget));
    gtk.Box.append(form_box, buttons.as(gtk.Widget));

    var form_scrolled = gtk.ScrolledWindow.new();
    gtk.ScrolledWindow.setChild(form_scrolled, form_box.as(gtk.Widget));
    gtk.Widget.setHexpand(form_scrolled.as(gtk.Widget), 1);
    gtk.Widget.setVexpand(form_scrolled.as(gtk.Widget), 1);
    gtk.Window.setChild(window, form_scrolled.as(gtk.Widget));
    gtk.Widget.show(window.as(gtk.Widget));
}

fn on_add_clicked(_: *gtk.Button, parent: *gtk.Window) callconv(.c) void {
    openForm(parent, null, -1);
}

fn on_edit_clicked(_: *gtk.Button, parent: *gtk.Window) callconv(.c) void {
    if (selected_id < 0) return;
    for (db.recipes) |r| {
        if (r.id == selected_id) {
            openForm(parent, r, selected_id);
            return;
        }
    }
}

fn on_delete_clicked(_: *gtk.Button, parent: *gtk.Window) callconv(.c) void {
    if (selected_id < 0) return;
    var title: [:0]const u8 = "";
    for (db.recipes) |r| {
        if (r.id == selected_id) {
            title = r.title;
            break;
        }
    }
    pending_delete_id = selected_id;
    var window = gtk.Window.new();
    gtk.Window.setTitle(window, "Delete recipe");
    gtk.Window.setTransientFor(window, parent);
    gtk.Window.setModal(window, 1);
    gtk.Window.setDefaultSize(window, 400, 150);
    var box = gtk.Box.new(.vertical, 6);
    const msg = fmtZ(std.heap.page_allocator, "Delete \"{s}\"? This cannot be undone.", .{title});
    var msg_label = gtk.Label.new(msg);
    gtk.Label.setWrap(msg_label, 1);
    gtk.Box.append(box, msg_label.as(gtk.Widget));
    var row = gtk.Box.new(.horizontal, 6);
    var confirm = gtk.Button.newWithLabel("Delete");
    _ = gtk.Button.signals.clicked.connect(confirm, *gtk.Window, &on_delete_confirm, window, .{});
    gtk.Box.append(row, confirm.as(gtk.Widget));
    var cancel = gtk.Button.newWithLabel("Cancel");
    _ = gtk.Button.signals.clicked.connect(cancel, *gtk.Window, &on_delete_cancel, window, .{});
    gtk.Box.append(row, cancel.as(gtk.Widget));
    gtk.Box.append(box, row.as(gtk.Widget));
    gtk.Window.setChild(window, box.as(gtk.Widget));
    gtk.Widget.show(window.as(gtk.Widget));
}

fn on_delete_confirm(_: *gtk.Button, window: *gtk.Window) callconv(.c) void {
    if (pending_delete_id < 0) {
        gtk.Window.close(window);
        return;
    }
    db.deleteRecipe(pending_delete_id) catch {
        // The dialog has no error label; surface the error
        // as the window title so the failure is visible.
        if (db.load_error) |e| {
            gtk.Window.setTitle(window, e);
        } else {
            gtk.Window.setTitle(window, "Could not delete the recipe.");
        }
        return;
    };
    pending_delete_id = -1;
    db.reload() catch {
        if (db.load_error) |e| {
            gtk.Window.setTitle(window, e);
        } else {
            gtk.Window.setTitle(window, "Could not reload recipes.");
        }
        return;
    };
    rebuild_list();
    if (filtered.items.len > 0) {
        selected_id = db.recipes[filtered.items[0]].id;
        show_recipe(detail_ptr, db.recipes[filtered.items[0]]);
        if (gtk.ListBox.getRowAtIndex(main_list_box, 0)) |row| {
            gtk.ListBox.selectRow(main_list_box, row);
        }
    } else {
        selected_id = -1;
        clear_detail(detail_ptr);
    }
    gtk.Window.close(window);
}

fn on_delete_cancel(_: *gtk.Button, window: *gtk.Window) callconv(.c) void {
    pending_delete_id = -1;
    gtk.Window.close(window);
}


fn activate(app: *gtk.Application, _: ?*anyopaque) callconv(.c) void {
    var window = gtk.ApplicationWindow.new(app);
    gtk.Window.setTitle(window.as(gtk.Window), "Recipe Manager");
    gtk.Window.setDefaultSize(window.as(gtk.Window), 900, 600);

    var list_box = gtk.ListBox.new();
    main_list_box = list_box;
    search_entry = gtk.SearchEntry.new();
    gtk.SearchEntry.setPlaceholderText(search_entry, "Type to filter recipes…");
    _ = gtk.SearchEntry.signals.search_changed.connect(search_entry, *gtk.Window, &on_search_changed, window.as(gtk.Window), .{});
    rebuild_list();
    var list_scrolled = gtk.ScrolledWindow.new();
    gtk.ScrolledWindow.setChild(list_scrolled, list_box.as(gtk.Widget));
    gtk.Widget.setSizeRequest(list_scrolled.as(gtk.Widget), 250, -1);

    var detail = std.heap.page_allocator.create(Detail) catch @panic("oom");
    detail_ptr = detail;
    detail.arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);

    var detail_box = gtk.Box.new(gtk.Orientation.vertical, 6);
    detail.title = detail_label();
    gtk.Box.append(detail_box, detail.title.as(gtk.Widget));
    detail.description = detail_label();
    gtk.Label.setWrap(detail.description, 1);
    gtk.Box.append(detail_box, detail.description.as(gtk.Widget));
    detail.servings = detail_label();
    gtk.Box.append(detail_box, detail.servings.as(gtk.Widget));
    gtk.Box.append(detail_box, detail_label_heading("Ingredients"));
    for (&detail.ingredient_labels) |*slot| {
        slot.* = detail_label();
        gtk.Box.append(detail_box, slot.*.as(gtk.Widget));
    }
    gtk.Box.append(detail_box, detail_label_heading("Steps"));
    for (&detail.step_labels) |*slot| {
        slot.* = detail_label();
        gtk.Box.append(detail_box, slot.*.as(gtk.Widget));
    }
    detail.notes = detail_label();
    gtk.Label.setWrap(detail.notes, 1);
    gtk.Box.append(detail_box, detail.notes.as(gtk.Widget));
    var edit_button = gtk.Button.newWithLabel("Edit recipe");
    _ = gtk.Button.signals.clicked.connect(edit_button, *gtk.Window, &on_edit_clicked, window.as(gtk.Window), .{});
    gtk.Box.append(detail_box, edit_button.as(gtk.Widget));
    var delete_button = gtk.Button.newWithLabel("Delete recipe");
    _ = gtk.Button.signals.clicked.connect(delete_button, *gtk.Window, &on_delete_clicked, window.as(gtk.Window), .{});
    gtk.Box.append(detail_box, delete_button.as(gtk.Widget));

    var detail_scrolled = gtk.ScrolledWindow.new();
    gtk.ScrolledWindow.setChild(detail_scrolled, detail_box.as(gtk.Widget));
    gtk.Widget.setHexpand(detail_scrolled.as(gtk.Widget), 1);
    gtk.Widget.setVexpand(detail_scrolled.as(gtk.Widget), 1);

    var add_button = gtk.Button.newWithLabel("Add recipe");
    _ = gtk.Button.signals.clicked.connect(add_button, *gtk.Window, &on_add_clicked, window.as(gtk.Window), .{});
    var left_box = gtk.Box.new(gtk.Orientation.vertical, 6);
    gtk.Box.append(left_box, search_entry.as(gtk.Widget));
    gtk.Box.append(left_box, add_button.as(gtk.Widget));
    gtk.Box.append(left_box, list_scrolled.as(gtk.Widget));

    var root = gtk.Box.new(gtk.Orientation.horizontal, 0);
    gtk.Box.append(root, left_box.as(gtk.Widget));
    gtk.Box.append(root, detail_scrolled.as(gtk.Widget));
    gtk.Window.setChild(window.as(gtk.Window), root.as(gtk.Widget));

    _ = gtk.ListBox.signals.row_selected.connect(list_box, *Detail, &on_row_selected, detail, .{});
    if (db.load_error) |err| {
        gtk.Label.setText(detail.title, err);
    } else if (filtered.items.len > 0) {
        show_recipe(detail, db.recipes[filtered.items[0]]);
        if (gtk.ListBox.getRowAtIndex(list_box, 0)) |row0| {
            gtk.ListBox.selectRow(list_box, row0);
        }
    }

    gtk.Widget.show(window.as(gtk.Widget));
}

fn detail_label_heading(text: [:0]const u8) *gtk.Widget {
    var label = gtk.Label.new(text);
    gtk.Label.setXalign(label, 0);
    return label.as(gtk.Widget);
}

pub fn main(init: std.process.Init) void {
    db.ensureLoaded(&seed_recipes);

    var app = gtk.Application.new("org.desktop-app-exploration.zig-gobject", .{});
    defer app.unref();
    _ = gio.Application.signals.activate.connect(app, ?*anyopaque, &activate, null, .{});
    const argv = init.minimal.args.vector;
    const status = gio.Application.run(app.as(gio.Application), @intCast(argv.len), @ptrCast(@constCast(argv.ptr)));
    std.process.exit(@intCast(status));
}
