// Form holds the add window's widgets. Heap-allocated like
// Detail: the window outlives the handler that opens it.
// Row lists come from the form's arena, never freed.
const Form = struct {
    window: *gtk.Window,
    edit_id: i64,
    title: *gtk.Entry,
    description: *gtk.Entry,
    servings: *gtk.SpinButton,
    notes: *gtk.Entry,
    // Image chosen via "Choose image…", copied into
    // images/ at choose time (like odin-gtk); saved with
    // the recipe. Empty means no image.
    image_path: [:0]const u8 = "",
    image_label: *gtk.Label,
    error_label: *gtk.Label,
    ing_box: *gtk.Box,
    step_box: *gtk.Box,
    ing_rows: std.ArrayList(IngredientRow),
    step_rows: std.ArrayList(StepRow),
    arena: std.heap.ArenaAllocator,
};

// Entry text as a sentinel slice. This points at the
// entry's own buffer, so it is only valid while the entry
// lives — fine here, since saving binds (SQLITE_STATIC)
// and steps before the form closes.
/// Basename of a sentinel path, still sentinel (the
/// suffix runs to the path's NUL terminator).
fn basenameZ(path: [:0]const u8) [:0]const u8 {
    const idx = std.mem.lastIndexOfScalar(u8, path, '/') orelse return path;
    return path[idx + 1 ..];
}

fn entryText(entry: *gtk.Entry) [:0]const u8 {
    return std.mem.span(gtk.Editable.getText(entry.as(gtk.Editable)));
}

fn isBlank(text: [:0]const u8) bool {
    return std.mem.trim(u8, text, " \t\r\n").len == 0;
}

fn add_list_row(list_box: *gtk.ListBox, title: [:0]const u8) void {
    var row_label = gtk.Label.new(title);
    gtk.Label.setXalign(row_label, 0);
    gtk.ListBox.append(list_box, row_label.as(gtk.Widget));
}

// rebuild_list builds one row box per filtered recipe:
// a 32x32 image slot (picture, spinner, or placeholder,
// exactly one visible) plus the title label. Row labels
// stay unselectable so clicks select the recipe.
fn add_image_row(list_box: *gtk.ListBox, recipe: db.Recipe) void {
    var row_box = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var slot = gtk.Box.new(gtk.Orientation.horizontal, 0);
    gtk.Widget.setSizeRequest(slot.as(gtk.Widget), 32, 32);
    var picture = gtk.Picture.new();
    gtk.Picture.setContentFit(picture, .scale_down);
    gtk.Widget.setSizeRequest(picture.as(gtk.Widget), 32, 32);
    var spinner = gtk.Spinner.new();
    var placeholder = gtk.Label.new("");
    gtk.Widget.setSizeRequest(placeholder.as(gtk.Widget), 32, 32);
    gtk.Box.append(slot, picture.as(gtk.Widget));
    gtk.Box.append(slot, spinner.as(gtk.Widget));
    gtk.Box.append(slot, placeholder.as(gtk.Widget));
    gtk.Widget.setVisible(picture.as(gtk.Widget), 0);
    gtk.Widget.setVisible(spinner.as(gtk.Widget), 0);
    gtk.Widget.setVisible(placeholder.as(gtk.Widget), 1);
    gtk.Box.append(row_box, slot.as(gtk.Widget));
    var row_label = gtk.Label.new(recipe.title);
    gtk.Label.setXalign(row_label, 0);
    gtk.Box.append(row_box, row_label.as(gtk.Widget));
    gtk.ListBox.append(list_box, row_box.as(gtk.Widget));
    if (recipe.image_path.len > 0) {
        image_row_refs.append(std.heap.page_allocator, .{
            .path = recipe.image_path,
            .picture = picture,
            .spinner = spinner,
            .placeholder = placeholder.as(gtk.Widget),
        }) catch {};
    }
}


fn apply_filter() void {
    filtered.clearRetainingCapacity();
    const query = std.mem.span(gtk.Editable.getText(search_entry.as(gtk.Editable)));
    for (db.recipes, 0..) |recipe, i| {
        if (search.titleMatchesSearch(recipe.title, query)) {
            filtered.append(std.heap.page_allocator, i) catch @panic("oom");
        }
    }
}

fn rebuild_list() void {
    apply_filter();
    gtk.ListBox.removeAll(main_list_box);
    image_row_refs.clearRetainingCapacity();
    for (filtered.items) |idx| {
        add_image_row(main_list_box, db.recipes[idx]);
    }
    start_image_loads();
}

fn add_ingredient_row(form: *Form) void {
    const alloc = form.arena.allocator();
    var row_box = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var amount = gtk.Entry.new();
    var unit = gtk.Entry.new();
    var name = gtk.Entry.new();
    gtk.Box.append(row_box, amount.as(gtk.Widget));
    gtk.Box.append(row_box, unit.as(gtk.Widget));
    gtk.Box.append(row_box, name.as(gtk.Widget));
    var remove = gtk.Button.newWithLabel("Remove");
    gtk.Box.append(row_box, remove.as(gtk.Widget));
    _ = gtk.Button.signals.clicked.connect(remove, *gtk.Widget, &on_remove_ingredient, row_box.as(gtk.Widget), .{});
    gtk.Box.append(form.ing_box, row_box.as(gtk.Widget));
    form.ing_rows.append(alloc, .{
        .box = row_box.as(gtk.Widget),
        .amount = amount,
        .unit = unit,
        .name = name,
    }) catch @panic("oom");
}

fn add_step_row(form: *Form) void {
    const alloc = form.arena.allocator();
    var row_box = gtk.Box.new(gtk.Orientation.horizontal, 6);
    var entry = gtk.Entry.new();
    gtk.Box.append(row_box, entry.as(gtk.Widget));
    var remove = gtk.Button.newWithLabel("Remove");
    gtk.Box.append(row_box, remove.as(gtk.Widget));
    _ = gtk.Button.signals.clicked.connect(remove, *gtk.Widget, &on_remove_step, row_box.as(gtk.Widget), .{});
    gtk.Box.append(form.step_box, row_box.as(gtk.Widget));
    form.step_rows.append(alloc, .{
        .box = row_box.as(gtk.Widget),
        .entry = entry,
    }) catch @panic("oom");
}

fn on_remove_ingredient(_: *gtk.Button, row_box: *gtk.Widget) callconv(.c) void {
    const form = active_form orelse return;
    for (form.ing_rows.items, 0..) |row, i| {
        if (row.box == row_box) {
            gtk.Box.remove(form.ing_box, row_box);
            _ = form.ing_rows.orderedRemove(i);
            return;
        }
    }
}

fn on_remove_step(_: *gtk.Button, row_box: *gtk.Widget) callconv(.c) void {
    const form = active_form orelse return;
    for (form.step_rows.items, 0..) |row, i| {
        if (row.box == row_box) {
            gtk.Box.remove(form.step_box, row_box);
            _ = form.step_rows.orderedRemove(i);
            return;
        }
    }
}

fn on_add_ingredient_row(_: *gtk.Button, form: *Form) callconv(.c) void {
    add_ingredient_row(form);
}

fn on_add_step_row(_: *gtk.Button, form: *Form) callconv(.c) void {
    add_step_row(form);
}

fn on_add_save(_: *gtk.Button, form: *Form) callconv(.c) void {
    const alloc = form.arena.allocator();
    const title = entryText(form.title);
    if (isBlank(title)) {
        gtk.Label.setText(form.error_label, "Title is required.");
        return;
    }
    var ingredients: std.ArrayList(db.Ingredient) = .empty;
    for (form.ing_rows.items) |row| {
        const amount = entryText(row.amount);
        const unit = entryText(row.unit);
        const name = entryText(row.name);
        if (isBlank(amount) and isBlank(unit) and isBlank(name)) continue;
        ingredients.append(alloc, .{
            .amount = amount,
            .unit = unit,
            .name = name,
        }) catch @panic("oom");
    }
    var steps: std.ArrayList([:0]const u8) = .empty;
    for (form.step_rows.items) |row| {
        const text = entryText(row.entry);
        if (isBlank(text)) continue;
        steps.append(alloc, text) catch @panic("oom");
    }
    var recipe = db.Recipe{
        .title = title,
        .description = entryText(form.description),
        .servings = @intCast(gtk.SpinButton.getValueAsInt(form.servings)),
        .image_path = form.image_path,
        .ingredients = ingredients.items,
        .steps = steps.items,
        .notes = entryText(form.notes),
    };
    var saved_id = form.edit_id;
    if (form.edit_id >= 0) {
        recipe.id = form.edit_id;
        db.updateRecipe(recipe) catch {
            if (db.load_error) |e| {
                gtk.Label.setText(form.error_label, e);
            } else {
                gtk.Label.setText(form.error_label, "Could not save the recipe.");
            }
            return;
        };
    } else {
        const id = db.insertRecipe(recipe) catch {
            if (db.load_error) |e| {
                gtk.Label.setText(form.error_label, e);
            } else {
                gtk.Label.setText(form.error_label, "Could not save the recipe.");
            }
            return;
        };
        saved_id = id;
    }
    db.reload() catch {
        if (db.load_error) |e| {
            gtk.Label.setText(form.error_label, e);
        } else {
            gtk.Label.setText(form.error_label, "Could not reload recipes.");
        }
        return;
    };
    rebuild_list();
    for (filtered.items, 0..) |idx, p| {
        if (db.recipes[idx].id == saved_id) {
            if (gtk.ListBox.getRowAtIndex(main_list_box, @intCast(p))) |row| {
                gtk.ListBox.selectRow(main_list_box, row);
            }
            break;
        }
    }
    active_form = null;
    gtk.Window.close(form.window);
}

