fn on_delete_clicked(_: *gtk.Button, parent: *gtk.Window) callconv(.c) void {
    if (selected_id < 0) return;
    var title: [:0]const u8 = "";
    for (db.recipes) |r| {
        if (r.id == selected_id) {
            title = r.title;
            break;
        }
    }
    pending_delete_id = selected_id;
    var window = gtk.Window.new();
    gtk.Window.setTitle(window, "Delete recipe");
    gtk.Window.setTransientFor(window, parent);
    gtk.Window.setModal(window, 1);
    gtk.Window.setDefaultSize(window, 400, 150);
    var box = gtk.Box.new(.vertical, 6);
    const msg = fmtZ(std.heap.page_allocator, "Delete \"{s}\"? This cannot be undone.", .{title});
    var msg_label = gtk.Label.new(msg);
    gtk.Label.setWrap(msg_label, 1);
    gtk.Box.append(box, msg_label.as(gtk.Widget));
    var row = gtk.Box.new(.horizontal, 6);
    var confirm = gtk.Button.newWithLabel("Delete");
    _ = gtk.Button.signals.clicked.connect(confirm, *gtk.Window, &on_delete_confirm, window, .{});
    gtk.Box.append(row, confirm.as(gtk.Widget));
    var cancel = gtk.Button.newWithLabel("Cancel");
    _ = gtk.Button.signals.clicked.connect(cancel, *gtk.Window, &on_delete_cancel, window, .{});
    gtk.Box.append(row, cancel.as(gtk.Widget));
    gtk.Box.append(box, row.as(gtk.Widget));
    gtk.Window.setChild(window, box.as(gtk.Widget));
    gtk.Widget.show(window.as(gtk.Widget));
}

fn on_delete_confirm(_: *gtk.Button, window: *gtk.Window) callconv(.c) void {
    if (pending_delete_id < 0) {
        gtk.Window.close(window);
        return;
    }
    db.deleteRecipe(pending_delete_id) catch {
        // The dialog has no error label; surface the error
        // as the window title so the failure is visible.
        if (db.load_error) |e| {
            gtk.Window.setTitle(window, e);
        } else {
            gtk.Window.setTitle(window, "Could not delete the recipe.");
        }
        return;
    };
    pending_delete_id = -1;
    db.reload() catch {
        if (db.load_error) |e| {
            gtk.Window.setTitle(window, e);
        } else {
            gtk.Window.setTitle(window, "Could not reload recipes.");
        }
        return;
    };
    rebuild_list();
    if (filtered.items.len > 0) {
        selected_id = db.recipes[filtered.items[0]].id;
        show_recipe(detail_ptr, db.recipes[filtered.items[0]]);
        if (gtk.ListBox.getRowAtIndex(main_list_box, 0)) |row| {
            gtk.ListBox.selectRow(main_list_box, row);
        }
    } else {
        selected_id = -1;
        clear_detail(detail_ptr);
    }
    gtk.Window.close(window);
}

fn on_delete_cancel(_: *gtk.Button, window: *gtk.Window) callconv(.c) void {
    pending_delete_id = -1;
    gtk.Window.close(window);
}



// --- File dialogs ---
//
// One dialog at a time (they are modal), so the purpose
// lives in a package var the async callback reads.

const DialogPurpose = enum { none, choose_image, import_file, export_single, export_all };

var dialog_purpose: DialogPurpose = .none;
var dialog_dialog: *gtk.FileDialog = undefined;

var main_io_threaded: ?std.Io.Threaded = null;

fn getMainIo() std.Io {
    if (main_io_threaded == null) {
        main_io_threaded = std.Io.Threaded.init(std.heap.page_allocator, .{});
    }
    return main_io_threaded.?.io();
}

fn open_file_dialog(purpose: DialogPurpose) void {
    dialog_purpose = purpose;
    const dialog = gtk.FileDialog.new();
    dialog_dialog = dialog;
    gtk.FileDialog.setModal(dialog, 1);
    switch (purpose) {
        .choose_image => gtk.FileDialog.setTitle(dialog, "Choose image"),
        .import_file => gtk.FileDialog.setTitle(dialog, "Import recipe JSON"),
        .export_single => {
            gtk.FileDialog.setTitle(dialog, "Export recipe");
            var initial: [:0]const u8 = "recipes.json";
            if (selected_id >= 0) {
                for (db.recipes) |r| {
                    if (r.id == selected_id) {
                        const name = json_export.defaultFileName(std.heap.page_allocator, r.title) catch "recipe.json";
                        initial = std.fmt.allocPrintSentinel(std.heap.page_allocator, "{s}", .{name}, 0) catch "recipe.json";
                        break;
                    }
                }
            }
            gtk.FileDialog.setInitialName(dialog, initial);
        },
        .export_all => {
            gtk.FileDialog.setTitle(dialog, "Export all recipes");
            gtk.FileDialog.setInitialName(dialog, "recipes.json");
        },
        .none => {},
    }
    if (purpose == .export_single or purpose == .export_all) {
        gtk.FileDialog.save(dialog, main_window, null, &on_dialog_done, null);
    } else {
        gtk.FileDialog.open(dialog, main_window, null, &on_dialog_done, null);
    }
}

fn on_choose_image(_: *gtk.Button, form: *Form) callconv(.c) void {
